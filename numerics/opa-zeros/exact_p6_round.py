"""Numerical step (NOT itself a proof): produce the data module checked by exact_p6_verify.py.

1. max-margin SDP of exact_p6_search.solve with free c1, f;
2. round c1, f to rationals with denominator FDEN and re-solve for the Gram matrices with c1, f fixed;
3. symmetrise and round all Gram matrices to integers over QDEN;
4. write exact_p6_data_<tag>.py (the projection of Q0 and all checks happen in the verifier).

Usage: exact_p6_round.py r d D0 D1 tag [FDEN] [QDEN] [p]     (p even, default 6; writes exact_p<p>_data_<tag>.py)
"""
import sys
import os
from fractions import Fraction
import numpy as np
import exact_p6_search as E

r = Fraction(sys.argv[1])
d, D0, D1 = map(int, sys.argv[2:5])
tag = sys.argv[5]
FDEN = int(sys.argv[6]) if len(sys.argv) > 6 else 10**4
QDEN = int(sys.argv[7]) if len(sys.argv) > 7 else 10**9
E.P = int(sys.argv[8]) if len(sys.argv) > 8 else 6

t, c1, f, _, _ = E.solve(r, d, D0, D1)
print(f"free solve: margin {t:.3e}, c1 = {c1:.6f}")
q = lambda v: Fraction(round(float(v) * FDEN), FDEN)
c1r = q(c1)
fr = {k: q(v) for k, v in f.items()}
t2, _, _, Qs, _ = E.solve(r, d, D0, D1, fixed=(c1r, fr))
print(f"fixed solve: margin {t2:.3e}, c1 = {c1r}")
rows = []
for Q in Qs:
    Q = (Q + Q.T) / 2
    Qi = np.rint(Q * QDEN).astype(np.int64)
    rows.append([" ".join(str(int(v)) for v in row) for row in Qi])
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), f"exact_p{E.P}_data_{tag}.py")
with open(path, "w") as fh:
    fh.write(f'"""Certificate data for exact_p6_verify.py (generated by exact_p6_round.py {" ".join(sys.argv[1:])}).\n'
             f'Gram entries are integers over den; Q = [Q0 even, Q0 odd, Q1 even, Q1 odd]."""\n')
    data = {"p": E.P, "r": str(r), "delta": "1/1000", "d": d, "D0": D0, "D1": D1, "c1": str(c1r),
            "f": {f"{m},{n}": str(v) for (m, n), v in sorted(fr.items()) if v != 0}, "den": QDEN, "Q": rows}
    fh.write("DATA = {\n")
    for k, v in data.items():
        if k == "Q":
            fh.write(' "Q": [\n')
            for blk in v:
                fh.write("  [\n" + "".join(f'   "{row}",\n' for row in blk) + "  ],\n")
            fh.write(" ],\n")
        else:
            fh.write(f" {k!r}: {v!r},\n")
    fh.write("}\n")
print("wrote", path)
