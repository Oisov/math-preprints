r"""Numerical (not a proof). Local ceiling of Jensen-enriched certificates (cutting planes).

Profiles G (H^2(C_+) boundary blow-ups) satisfy, besides int G^m dt = 0 (m >= 2), the Jensen
inequalities  int ( log|1 - G/a| + Re(G/a) ) dt >= 0  (a != 0).  So a local certificate
  Re g(h) - k Im g(h) >= Re sum_{m=2}^p F_m h^m + sum_j c_j ( log|1 - h/a_j| + Re(h/a_j) ),
c_j >= 0, gives Re((1+ik) B_p(G)) >= 0 for every profile, hence w = k/sqrt(1+k^2) is at most
the profile ceiling.  LP in (F, c, k) with poles a_j near the truncated atoms; the h-constraints
are generated by cutting planes (the remainder / |h|^2 is checked on a fine polar grid
|h| <= 12 and the most violated points are added) until the violation is < tol.
With c = 0 this is the truncated (polynomial) ceiling of evenp_local.py.
Usage: evenp_jensen.py 6 [cmax [nr nt]]   (c_j <= cmax for conditioning)
"""
import sys
import numpy as np
from scipy.optimize import linprog

p = int(sys.argv[1]) if len(sys.argv) > 1 else 6
kk = p // 2
cmax = float(sys.argv[2]) if len(sys.argv) > 2 else 5.0
# candidate poles: small discs around the atoms of the extremal truncated measure
# (output of the refinement in evenp_local.py's LP; p = 6 values hard-coded)
atoms = np.array([0.138 - 0.1527j, 0.1898 - 0.1967j, -0.1802 + 0.5615j, -0.1606 + 0.7277j,
                  1.0556 - 0.4157j, 0.4310 + 1.3681j, 1.5707 + 0.2849j, 1.2512 + 1.1857j,
                  1.3546 + 1.0793j])
a = np.array([z + 0.04 * u * np.exp(1j * v) for z in atoms for u in (0, 0.5, 1)
              for v in (np.linspace(0, 2 * np.pi, 6, endpoint=False) if u else [0])])
if len(sys.argv) > 3:  # optional extra polar grid of poles: nr x nt on 0.3 <= |a| <= 2.2
    nr, nt = int(sys.argv[3]), int(sys.argv[4])
    a = np.concatenate([a, (np.linspace(0.3, 2.2, nr)[:, None]
                            * np.exp(2j * np.pi * (np.arange(nt) + 0.5) / nt)).ravel()])


def columns(h):
    sc = 1 / np.abs(h) ** 2
    g = (1 - (1 - h) ** kk * np.conj(1 - h) ** (kk - 1)) * np.conj(h) * sc
    cols = []
    for m in range(2, p + 1):
        v = h ** m * sc
        cols += [v.real, -v.imag]
    for aj in a:
        z = h / aj
        with np.errstate(divide="ignore"):
            cols.append((np.log(np.abs(1 - z)) + z.real) * sc)
    A = np.array(cols).T
    A[~np.isfinite(A)] = -1e8
    return A, g


nF = 2 * (p - 1)
rf = np.concatenate([np.geomspace(1e-3, 0.1, 20), np.linspace(0.1, 4, 1200), np.geomspace(4, 12, 60)])
tf = 2 * np.pi * np.arange(1440) / 1440
H = (rf[:, None] * np.exp(1j * tf[None, :]))
r0 = np.concatenate([np.geomspace(1e-3, 0.1, 6), np.linspace(0.12, 4, 60), np.geomspace(4.5, 12, 8)])
t0 = 2 * np.pi * np.arange(120) / 120
pts = (r0[:, None] * np.exp(1j * t0)).ravel()
for jensen in ((False, True) if len(sys.argv) <= 3 else (True,)):
    P = pts.copy()
    for it in range(30):
        A, g = columns(P)
        nv = A.shape[1] + 1
        bd = [(None, None)] * nF + [(0, cmax if jensen else 0)] * (nv - 1 - nF) + [(None, None)]
        cost = np.zeros(nv)
        cost[-1] = -1
        res = linprog(cost, A_ub=np.hstack([A, g.imag[:, None]]), b_ub=g.real, bounds=bd, method="highs")
        if res.x is None:
            print("LP failed:", res.message)
            break
        x = res.x
        k = x[-1]
        # check on the fine grid, row by row
        viol, add = 0.0, []
        for row in H:
            Ar, gr = columns(row)
            rem = gr.real - k * gr.imag - Ar @ x[:-1]
            i = np.argmin(rem)
            if rem[i] < -1e-8:
                add.append(row[i])
                viol = min(viol, rem[i])
        print(f"p={p} jensen={jensen} it={it}: k={k:.8f} w={k / np.sqrt(1 + k * k):.8f} "
              f"min remainder on fine grid {viol:.2e} ({len(add)} cuts)", flush=True)
        if not add:
            break
        P = np.concatenate([P, np.array(add)])
    c = x[nF:-1]
    print("  active poles:", [(complex(np.round(a[i], 3)), round(float(c[i]), 4)) for i in np.argsort(-c)[:8] if c[i] > 1e-8])
